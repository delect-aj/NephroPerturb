#!/usr/bin/env python
"""Generate config/renal_cases.yaml from the Stage-2 QC-passed cohort
signatures (real GEO biopsies), replacing the demo seeds.

Selects up to 10 representative cohorts (DKD, LN, IgAN, CKD, AKI across
glomerulus/tubulointerstitium compartments) and writes full provenance:
gse, pmid (from the series metadata when available), platform, n_disease,
n_control, compartment, matrix_sha256, top_n=150.
"""
import gzip
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))
from common import paths  # noqa: E402

RAW = paths()["store"] / "annotations" / "raw" / "bm2_20261120"
SIGS = ROOT / "benchmarks" / "outputs" / "bm2_cohort_signatures.json"
OUT = ROOT / "config" / "renal_cases.yaml"

PREFERRED = [
    "DKD_glom", "DKD_tub", "ERCB_DKD_glom", "LN_glom", "LN_tub", "LN2",
    "ERCB_LN_glom", "ERCB_IgAN_glom", "CKD", "AKI",
]
DISPLAY = {
    "DKD": "Diabetic kidney disease",
    "LN": "Lupus nephritis",
    "IgAN": "IgA nephropathy",
    "CKD": "Chronic kidney disease",
    "AKI": "Acute kidney injury",
    "FSGS": "Focal segmental glomerulosclerosis",
}


def pmid_of(gse):
    path = RAW / gse / "matrix.txt.gz"
    if path.exists():
        with gzip.open(path, "rt", errors="replace") as fh:
            for line in fh:
                if line.startswith("!Series_pubmed_id"):
                    values = [v.strip().strip('"') for v in line.split("\t")[1:]]
                    values = [v for v in values if v]
                    if values:
                        return ",".join(values)
                if line.startswith("!series_matrix_table_begin"):
                    break
    return ""


def main():
    data = json.loads(SIGS.read_text())["cohorts"]
    cases = {}
    for cid in PREFERRED:
        spec = data.get(cid)
        if not spec or not spec.get("passed"):
            continue
        prov = spec["provenance"]
        cases[cid] = {
            "disease_name": DISPLAY.get(spec["disease"], spec["disease"]),
            "disease_code": spec["disease"],
            "compartment": spec.get("compartment") or prov.get("series", ""),
            "gse": spec["gse"],
            "study_id": spec.get("study_id", spec["gse"]),
            "platform": prov.get("platform", ""),
            "n_disease": prov.get("n_disease"),
            "n_control": prov.get("n_control"),
            "matrix_sha256": prov.get("matrix_sha256", ""),
            "top_n": prov.get("top_n", 150),
            "pmid": pmid_of(spec["gse"]),
            "dataset_accession": spec["gse"],
            "up": spec["up"],
            "down": spec["down"],
        }
    if len(cases) < 6:
        raise SystemExit(f"only {len(cases)} cohorts available; need >= 6")
    OUT.write_text(
        "# BM-2 real human renal-biopsy cohorts (generated by\n"
        "# scripts/etl/build_renal_cases.py from QC-passed GEO signatures).\n"
        "# Each case carries full provenance: GSE, platform, group sizes,\n"
        "# matrix SHA256, PMID (when deposited) and top-150 up/down genes.\n"
        + yaml.safe_dump({"cases": cases}, sort_keys=False, allow_unicode=True,
                         width=120))
    print(f"[cases] wrote {len(cases)} real cohorts -> {OUT}: {sorted(cases)}")


if __name__ == "__main__":
    main()
